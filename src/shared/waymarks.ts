export type WaymarkCategory = keyof typeof SITES;

export const WAYMARK_CATEGORIES = Object.keys(SITES) as WaymarkCategory[];

export const WAYMARKS: readonly Waymark[] = WAYMARK_CATEGORIES.flatMap(
  (category) =>
    (SITES[category] as readonly Site[]).map(([name, keyword, url]) => ({
      name,
      keyword,
      url,
      category,
    })),
);

/**
 * Everyday English and German words no waymark may use as its keyword. A
 * keyword and a space takes over the address field, so `so what` would turn
 * into a Stack Overflow search if `so` were one. A person can still choose
 * any of these for a shortcut of their own.
 */
