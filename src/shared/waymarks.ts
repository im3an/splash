/**
 * Waymarks: the catalog of search shortcuts. A waymark is the sign on a trail
 * that says where a path goes; here, `imdb` goes to IMDb. The list ships with
 * Splash, so browsing it sends nothing anywhere, and adding one just saves a
 * search shortcut.
 */

/** What the store is called, in one place. */
export const WAYMARKS_NAME = 'Waymarks';

export interface Waymark {
  name: string;
  /** Typed before the search words. Lower case, and unique in the catalog. */
  keyword: string;
  /** An https address with `%s` where the search words go. */
  url: string;
  category: WaymarkCategory;
}

type Site = readonly [name: string, keyword: string, url: string];

