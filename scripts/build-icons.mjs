const paths = (file) =>
  [
    ...readFileSync(dir + file, 'utf8').matchAll(/<path[^>]*\sd="([^"]+)"/g),
  ].map((m) => m[1]);

const lines = Object.entries(ICONS).map(([name, fluent]) => {
  const regular = paths(`${fluent}_20_regular.svg`);
  const filled = paths(`${fluent}_20_filled.svg`);
  return `  ${name}: [${JSON.stringify(regular)}, ${JSON.stringify(filled)}],`;
});

writeFileSync(
  new URL('../src/renderer/icons/fluent-paths.ts', import.meta.url),
  `// Generated by scripts/build-icons.mjs from @fluentui/svg-icons (MIT). Don't edit.\n` +
    `export const FLUENT_PATHS = {\n${lines.join('\n')}\n} as const satisfies Record<string, readonly [readonly string[], readonly string[]]>;\n`,
);
console.log(`Wrote ${lines.length} icons`);
